#!/usr/bin/env bash
# Full experiment suite for the ABIDE-I paper, consolidated into ONE directory.
#
#   ./run_full_study.sh            # 10-fold, everything
#   FOLDS=5 ./run_full_study.sh    # faster pass
#
# Layout produced:
#   results/<timestamp>_full_study/
#     ablations/   representation, classifier, rank, atlas, fusion, harmonisation,
#                  protocol, statistics, leakage_audit  (each .csv + .json)
#       figures/   one figure per experiment
#     model/       headline model (copied from the latest completed model run)
#     STUDY.md     index with the headline numbers
set -e
cd "$(dirname "$0")"
PY=.venv/bin/python
export OMP_NUM_THREADS=${OMP_NUM_THREADS:-6}
export KMP_DUPLICATE_LIB_OK=TRUE
FOLDS=${FOLDS:-10}

STAMP=$(date +%Y-%m-%d_%H-%M-%S)
STUDY="results/${STAMP}_full_study"
ABL="$STUDY/ablations"
mkdir -p "$ABL"
echo "=== full study -> $STUDY (folds=$FOLDS) ==="

# ---- Experiment 7: leakage audit (independent, run first so it always lands) ----
echo "--- [1/3] leakage audit ---"
$PY leakage_audit.py --n_folds "$FOLDS" --out "$ABL" 2>&1 | grep -avE "resource_tracker" || true

# ---- Experiments 1-3: the novelties ----
echo "--- [2/3] representation / classifier / rank ---"
$PY run_ablations.py --experiments representation classifier rank \
    --n_folds "$FOLDS" --window 50 --n_windows 6 \
    --out_dir results --run_name tmp_novelty 2>&1 | grep -avE "resource_tracker" || true
NOV=$(ls -dt results/*_tmp_novelty 2>/dev/null | head -1)
[ -n "$NOV" ] && cp -f "$NOV"/ablations/*.csv "$NOV"/ablations/*.json "$ABL"/ 2>/dev/null || true

# ---- Experiments 4-6, 8-9: design, protocol, statistics ----
echo "--- [3/3] atlas / fusion / harmonisation / protocol / statistics ---"
$PY run_ablations.py --experiments atlas fusion harmonisation protocol statistics \
    --n_folds "$FOLDS" \
    --out_dir results --run_name tmp_design 2>&1 | grep -avE "resource_tracker" || true
DES=$(ls -dt results/*_tmp_design 2>/dev/null | head -1)
[ -n "$DES" ] && cp -f "$DES"/ablations/*.csv "$DES"/ablations/*.json "$ABL"/ 2>/dev/null || true

# ---- merge the two ablations_all.csv files ----
$PY - "$ABL" <<'PY'
import sys, glob, os
import pandas as pd
abl = sys.argv[1]
parts = [pd.read_csv(f) for f in glob.glob(os.path.join(abl, "*.csv"))
         if os.path.basename(f) not in ("ablations_all.csv", "leakage_audit.csv")
         and "experiment" in pd.read_csv(f, nrows=0).columns]
if parts:
    df = pd.concat(parts, ignore_index=True).drop_duplicates(
        subset=["experiment", "condition"], keep="last")
    df.to_csv(os.path.join(abl, "ablations_all.csv"), index=False)
    print(f"merged {len(df)} conditions -> ablations_all.csv")
PY

# ---- figures ----
echo "--- figures ---"
$PY viz_ablations.py --dir "$ABL" 2>&1 | tail -20 || true

# ---- bring in the headline model run ----
MODEL=$(ls -dt results/*_final 2>/dev/null | grep -v combat | head -1)
if [ -n "$MODEL" ] && [ -d "$MODEL/model" ]; then
  cp -R "$MODEL/model" "$STUDY/model" 2>/dev/null || true
  echo "model copied from $MODEL"
fi

# ---- index ----
$PY - "$STUDY" <<'PY'
import sys, os, json, glob
import pandas as pd
study = sys.argv[1]
abl = os.path.join(study, "ablations")
lines = ["# ABIDE-I study — consolidated results\n",
         "Generated by `run_full_study.sh`. Every condition has a CSV and a JSON in "
         "`ablations/`; figures are in `ablations/figures/`.\n"]
f = os.path.join(abl, "ablations_all.csv")
if os.path.exists(f):
    df = pd.read_csv(f)
    for exp, g in df.groupby("experiment"):
        lines.append(f"\n## {exp}\n")
        lines.append("| condition | AUROC | accuracy |")
        lines.append("|---|---|---|")
        for _, r in g.sort_values("auroc", ascending=False).iterrows():
            lines.append(f"| {r['condition']} | {r['auroc']:.3f} ± {r.get('auroc_std', 0):.3f} "
                         f"| {r['accuracy']:.3f} |")
f = os.path.join(abl, "leakage_audit.csv")
if os.path.exists(f):
    d = pd.read_csv(f).sort_values("auroc")
    lines.append("\n## leakage audit (Experiment 7)\n")
    lines.append("| variant | AUROC | inflation vs honest |")
    lines.append("|---|---|---|")
    for _, r in d.iterrows():
        inf = r.get("auroc_inflation", float("nan"))
        lines.append(f"| {r['variant']} | {r['auroc']:.3f} | "
                     f"{'' if r['variant']=='honest' else f'+{inf:.3f}'} |")
open(os.path.join(study, "STUDY.md"), "w").write("\n".join(lines) + "\n")
print("index ->", os.path.join(study, "STUDY.md"))
PY

# ---- clean the temporary per-stage directories ----
rm -rf results/*_tmp_novelty results/*_tmp_design 2>/dev/null || true
ln -sfn "$(basename "$STUDY")" results/latest_study

echo "=== done: $STUDY ==="
find "$STUDY" -maxdepth 2 -type d | sort
